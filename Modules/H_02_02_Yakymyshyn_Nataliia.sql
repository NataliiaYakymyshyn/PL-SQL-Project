DECLARE
  v_department_id  hr.employees.department_id%TYPE := 80;
  v_def_percent    VARCHAR2(30);
  v_percent        VARCHAR2(5);
BEGIN
  FOR dd IN (
    SELECT em.first_name || ' ' || em.last_name AS emp_name,
           em.manager_id,
           em.commission_pct * 100 AS percent_of_salary
    FROM hr.employees em
    WHERE em.department_id = v_department_id
    ORDER BY em.first_name
  ) LOOP

    IF dd.manager_id = 100 THEN
      DBMS_OUTPUT.PUT_LINE('???????????? – '||dd.emp_name||', ??????? ?? ???????? ?? ????? ???????????');
      CONTINUE;
    END IF;

    IF dd.percent_of_salary BETWEEN 10 AND 20 THEN
      v_def_percent := '???????????';
    ELSIF dd.percent_of_salary BETWEEN 25 AND 30 THEN
      v_def_percent := '????????';
    ELSIF dd.percent_of_salary BETWEEN 35 AND 40 THEN
      v_def_percent := '????????????';
    END IF;

    v_percent := CONCAT(dd.percent_of_salary, '%');

    DBMS_OUTPUT.PUT_LINE('???????????? – '||dd.emp_name||'; ??????? ?? ???????? – '||v_percent||'; ???? ???????? – '||v_def_percent);

  END LOOP;
END;

